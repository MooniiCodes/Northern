'use strict';

const fs = require('fs');
const path = require('path');
const { spawn } = require('child_process');
const { getEnvironment, toolEnv } = require('./sdk');
const {
  readMeta,
  collectBuildSources,
  combinedAuricSource
} = require('./projects');

const activePreviews = new Map();
const ROOT = path.resolve(__dirname, '..', '..');
const EMULATOR_DIR = path.join(ROOT, 'emulator');

function previewDir(dir) {
  return path.join(dir, '.preview');
}

function previewBinary(dir) {
  return path.join(previewDir(dir), 'aurora-preview');
}

function previewSd(dir) {
  return path.join(previewDir(dir), 'sd');
}

function streamLines(stream, onLine) {
  let buffer = '';
  stream.setEncoding('utf8');
  stream.on('data', (chunk) => {
    buffer += chunk;
    let index;
    while ((index = buffer.indexOf('\n')) >= 0) {
      onLine(buffer.slice(0, index).replace(/\r$/, ''));
      buffer = buffer.slice(index + 1);
    }
  });
  stream.on('end', () => {
    if (buffer) onLine(buffer.replace(/\r$/, ''));
    buffer = '';
  });
}

function missingPreviewHelp(env) {
  const lines = [];
  if (!env.preview.cc) {
    lines.push('No C compiler found (cc, gcc or clang).');
    lines.push('Install build-essential (Debian/Ubuntu) or base-devel (Arch).');
  }
  if (!env.preview.sdl2) {
    lines.push('SDL2 development files were not found.');
    lines.push('Arch:   sudo pacman -S sdl2');
    lines.push('Debian: sudo apt install libsdl2-dev');
    lines.push('Fedora: sudo dnf install SDL2-devel');
  }
  if (env.preview.cc && env.preview.sdl2) return '';
  return [
    'The PC preview needs a C compiler and SDL2.',
    '',
    ...lines,
    '',
    'The built-in preview does not need devkitARM or a 3DS emulator.'
  ].join('\n');
}

function runCommand(command, args, options, onOutput) {
  return new Promise((resolve) => {
    let child;
    let log = '';
    try {
      child = spawn(command, args, {
        ...options,
        env: options.env || process.env,
        windowsHide: true
      });
    } catch (error) {
      const text = `Could not start ${command}: ${error.message}\n`;
      onOutput({ stream: 'stderr', text });
      resolve({ ok: false, code: 1, log: text });
      return;
    }
    const push = (stream, line) => {
      log += line + '\n';
      onOutput({ stream, text: line + '\n' });
    };
    streamLines(child.stdout, (line) => push('stdout', line));
    streamLines(child.stderr, (line) => push('stderr', line));
    child.on('error', (error) => {
      const text = `${command}: ${error.message}\n`;
      log += text;
      onOutput({ stream: 'stderr', text });
      resolve({ ok: false, code: 1, log });
    });
    child.on('close', (code) => {
      resolve({ ok: code === 0, code: code ?? 1, log });
    });
  });
}

function auricEmitCommand(env, combinedPath, cPath) {
  return {
    command: env.python,
    // Run from auric-lang as a module; see builder.js for why.
    args: ['-m', 'compiler.aurc', 'emit-c', combinedPath, '-o', cPath],
    cwd: env.sdk.auricRoot
  };
}

async function buildPreviewBinary(dir, meta, env, onOutput) {
  const outDir = previewDir(dir);
  fs.mkdirSync(outDir, { recursive: true });
  fs.mkdirSync(path.join(outDir, 'sd', 'Aurora', 'Apps', 'C'), { recursive: true });
  fs.mkdirSync(path.join(outDir, 'sd', 'Aurora', 'Apps'), { recursive: true });

  const cc = env.preview.cc;
  const output = previewBinary(dir);
  const includeArgs = [
    '-I', EMULATOR_DIR,
    '-I', path.join(env.sdk.root, 'sdk', 'include'),
    '-I', path.join(env.sdk.root, 'include'),
    '-I', path.join(dir, 'src'),
    '-I', dir,
    '-I', path.join(dir, 'include')
  ];
  const defs = env.preview.sdl2Image ? ['-DAURORA_HAVE_SDL_IMAGE'] : [];
  const sources = [];

  if (meta.language === 'auric') {
    if (!env.python) {
      throw new Error('Python 3 is needed to compile Auric for the preview.');
    }
    const combined = combinedAuricSource(dir, meta);
    if (!combined.files.length) throw new Error('This Auric project has no .aur files.');
    const combinedPath = path.join(outDir, `${meta.slug}.aur`);
    fs.writeFileSync(
      combinedPath,
      `// Generated by Aurora3DS Studio from ${combined.files.length} file(s).\n` +
        combined.source,
      'utf8'
    );
    const cPath = path.join(outDir, 'auric.c');
    onOutput({ stream: 'info', text: `Transpiling ${combined.files.length} Auric file(s)...\n` });
    const emit = auricEmitCommand(env, combinedPath, cPath);
    const emitted = await runCommand(emit.command, emit.args, {
      cwd: emit.cwd,
      env: toolEnv({})
    }, onOutput);
    if (!emitted.ok || !fs.existsSync(cPath)) {
      throw new Error('Auric transpile failed.');
    }
    sources.push(cPath);
    sources.push(path.join(EMULATOR_DIR, 'auric_shim.c'));
    sources.push(path.join(EMULATOR_DIR, 'auric_main.c'));
    includeArgs.push('-I', path.join(env.sdk.auricRuntime));
  } else {
    const projectSources = collectBuildSources(dir, meta);
    if (!projectSources.length) throw new Error('This C project has no .c or .s files.');
    for (const rel of projectSources) sources.push(path.join(dir, rel));
  }

  sources.push(path.join(EMULATOR_DIR, 'runtime.c'));

  const args = [
    '-std=c11',
    '-O2',
    '-g',
    '-Wall',
    ...defs,
    ...includeArgs,
    '-o',
    output,
    ...sources,
    ...String(env.preview.flags || '').split(/\s+/).filter(Boolean),
    '-lm'
  ];

  onOutput({
    stream: 'info',
    text: `Compiling PC preview with ${path.basename(cc)}...\n`
  });
  onOutput({ stream: 'info', text: `  ${cc} ${args.map((a) => JSON.stringify(a)).join(' ')}\n` });
  const result = await runCommand(cc, args, {
    cwd: dir,
    env: toolEnv({})
  }, onOutput);
  if (!result.ok) throw new Error('PC preview build failed.');
  if (!fs.existsSync(output)) throw new Error('The preview binary was not produced.');
  try { fs.chmodSync(output, 0o755); } catch {}
  return output;
}

function previewEnvironment(dir, meta) {
  const sd = previewSd(dir);
  const isAuric = meta.language === 'auric';
  const appPath = isAuric
    ? `/Aurora/Apps/${meta.slug}.bin`
    : `/Aurora/Apps/C/${meta.slug}.bin`;
  const appDir = isAuric
    ? `/Aurora/Apps/${meta.slug}`
    : `/Aurora/Apps/C/${meta.slug}`;
  const appDirHost = path.join(sd, appDir.replace(/^\/+/, ''));
  fs.mkdirSync(appDirHost, { recursive: true });
  return {
    ...toolEnv({}),
    AURORA_PREVIEW_SD: sd,
    AURORA_APP_PATH: appPath,
    AURORA_APP_DIR: appDir,
    AURORA_APP_NAME: meta.name
  };
}

function startPreview({ dir, config, onOutput = () => {}, onExit = () => {} }) {
  const projectDir = path.resolve(dir);
  const existing = activePreviews.get(projectDir);
  if (existing) {
    try { existing.child.kill('SIGTERM'); } catch {}
    activePreviews.delete(projectDir);
  }

  const meta = readMeta(projectDir);
  const env = getEnvironment(config);
  const missing = missingPreviewHelp(env);
  if (missing) {
    onOutput({ stream: 'stderr', text: missing + '\n' });
    return Promise.resolve({ ok: false, missing: true, error: missing });
  }
  if (!env.sdk) {
    onOutput({
      stream: 'stderr',
      text: 'AuroraOS SDK not found. Set it in Settings before running the preview.\n'
    });
    return Promise.resolve({ ok: false, missing: true, error: 'SDK not found' });
  }

  return buildPreviewBinary(projectDir, meta, env, onOutput).then((binary) => {
    const child = spawn(binary, [], {
      cwd: projectDir,
      env: previewEnvironment(projectDir, meta),
      windowsHide: true
    });
    activePreviews.set(projectDir, { child, startedAt: Date.now() });
    onOutput({ stream: 'info', text: `\nRunning ${meta.name} in the PC preview.\n` });
    onOutput({
      stream: 'info',
      text: 'Keys: arrows = D-pad, A/B/X/Y = face buttons, Enter = START, ' +
        'Backspace = SELECT, Q/E = L/R, mouse = touch, Esc = close.\n'
    });
    streamLines(child.stdout, (line) => onOutput({ stream: 'stdout', text: line + '\n' }));
    streamLines(child.stderr, (line) => onOutput({ stream: 'stderr', text: line + '\n' }));
    child.on('error', (error) => {
      onOutput({ stream: 'stderr', text: `Preview error: ${error.message}\n` });
    });
    child.on('close', (code, signal) => {
      activePreviews.delete(projectDir);
      onExit({ code, signal });
    });
    return { ok: true, pid: child.pid, binary };
  }).catch((error) => {
    onOutput({ stream: 'stderr', text: `${error.message}\n` });
    return { ok: false, error: error.message };
  });
}

function stopPreview(dir) {
  const projectDir = path.resolve(dir);
  const entry = activePreviews.get(projectDir);
  if (!entry) return false;
  try { entry.child.kill('SIGTERM'); } catch {}
  activePreviews.delete(projectDir);
  return true;
}

function isPreviewRunning(dir) {
  return activePreviews.has(path.resolve(dir));
}

function stopAllPreviews() {
  for (const [dir, entry] of activePreviews) {
    try { entry.child.kill('SIGTERM'); } catch {}
    activePreviews.delete(dir);
  }
}

module.exports = {
  previewDir,
  previewBinary,
  previewSd,
  missingPreviewHelp,
  buildPreviewBinary,
  startPreview,
  stopPreview,
  isPreviewRunning,
  stopAllPreviews
};
