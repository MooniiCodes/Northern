'use strict';

const fs = require('fs');
const path = require('path');
const { spawn } = require('child_process');
const {
  readMeta,
  collectBuildSources,
  combinedAuricSource
} = require('./projects');
const { getEnvironment, toolEnv } = require('./sdk');

const activeBuilds = new Map();

function outputPath(dir, meta) {
  return path.join(dir, 'dist', `${meta.slug}.bin`);
}

function iconPath(dir, meta) {
  return path.join(dir, meta.icon || 'icon.icon');
}

function friendlyMissing(env) {
  if (!env.sdkPath) {
    return [
      'AuroraOS SDK not found.',
      '',
      'Set the SDK folder in Settings. It should contain:',
      '  sdk/aurcc.py',
      '  auric-lang/compiler/aurc.py',
      '  include/aurora.h',
      '',
      'The studio also looks in ~/Documents/Aurora3DS, ~/Documents/Aurora3DS/SDK',
      'and ~/Documents/AuroraOS.'
    ].join('\n');
  }
  if (!env.python) {
    return [
      'Python 3 was not found.',
      '',
      'Install Python 3 and put it on PATH, or choose the interpreter in Settings.',
      'Auric and the C SDK build tools are Python programs.'
    ].join('\n');
  }
  if (!env.devkit) {
    return [
      'devkitARM was not found (arm-none-eabi-gcc).',
      '',
      'Install devkitPro/devkitARM from https://devkitpro.org/wiki/Getting_Started',
      'and put its bin folder on PATH, or set "Toolchain bin folder" in Settings.',
      '',
      'Common paths:',
      '  /opt/devkitpro/devkitARM/bin',
      '  ~/devkitpro/devkitARM/bin',
      '  C:\\devkitPro\\devkitARM\\bin'
    ].join('\n');
  }
  return '';
}

function streamLines(stream, onLine) {
  let buffer = '';
  stream.setEncoding('utf8');
  stream.on('data', (chunk) => {
    buffer += chunk;
    let index;
    while ((index = buffer.indexOf('\n')) >= 0) {
      const line = buffer.slice(0, index).replace(/\r$/, '');
      buffer = buffer.slice(index + 1);
      onLine(line);
    }
  });
  stream.on('end', () => {
    if (buffer) onLine(buffer.replace(/\r$/, ''));
    buffer = '';
  });
}

function buildCommand(env, dir, meta) {
  const out = outputPath(dir, meta);
  const icon = iconPath(dir, meta);
  const buildDir = path.join(dir, '.build');

  if (meta.language === 'auric') {
    const combined = combinedAuricSource(dir, meta);
    if (!combined.files.length) {
      throw new Error('This Auric project has no .aur files.');
    }
    const combinedPath = path.join(buildDir, `${meta.slug}.aur`);
    fs.mkdirSync(buildDir, { recursive: true });
    fs.writeFileSync(
      combinedPath,
      `// Generated by Aurora3DS Studio from ${combined.files.length} file(s).\n` +
        combined.source,
      'utf8'
    );
    return {
      command: env.python,
      // Run as a module from auric-lang so Python finds the stdlib `ast`
      // module instead of compiler/ast.py (Python 3.12+ imports ast from
      // dataclasses during start-up).
      args: [
        '-m',
        'compiler.aurc',
        'build',
        combinedPath,
        '-o',
        out,
        '--icon',
        icon,
        '--build-dir',
        path.join(buildDir, 'auric')
      ],
      cwd: env.sdk.auricRoot,
      output: out,
      sources: combined.files,
      combinedPath
    };
  }

  const sources = collectBuildSources(dir, meta);
  if (!sources.length) {
    throw new Error('This C project has no .c or .s files.');
  }
  const args = [
    env.sdk.aurcc,
    'build',
    ...sources.map((rel) => path.join(dir, rel)),
    '-o',
    out,
    '--icon',
    icon,
    '--build-dir',
    path.join(buildDir, 'c'),
    '-I',
    path.join(dir, 'src'),
    '-I',
    dir,
    '-I',
    path.join(dir, 'include')
  ];
  return {
    command: env.python,
    args,
    cwd: dir,
    output: out,
    sources
  };
}

function buildProject({ dir, config, onOutput = () => {} }) {
  const projectDir = path.resolve(dir);
  const meta = readMeta(projectDir);
  const env = getEnvironment(config);
  const missing = friendlyMissing(env);
  if (missing) {
    onOutput({ stream: 'stderr', text: missing + '\n' });
    return Promise.resolve({ ok: false, code: 1, log: missing, output: null, missing: true });
  }

  let cmd;
  try {
    cmd = buildCommand(env, projectDir, meta);
  } catch (error) {
    onOutput({ stream: 'stderr', text: `${error.message}\n` });
    return Promise.resolve({ ok: false, code: 1, log: error.message, output: null });
  }

  const label = `${meta.name} (${meta.language === 'auric' ? 'Auric' : 'C SDK'})`;
  onOutput({ stream: 'info', text: `Building ${label}\n` });
  onOutput({ stream: 'info', text: `  ${cmd.command} ${cmd.args.map((a) => JSON.stringify(a)).join(' ')}\n` });

  return new Promise((resolve) => {
    let log = '';
    let finished = false;
    let child;
    try {
      child = spawn(cmd.command, cmd.args, {
        cwd: cmd.cwd,
        env: toolEnv(config),
        windowsHide: true
      });
    } catch (error) {
      const text = `Could not start the compiler: ${error.message}\n`;
      onOutput({ stream: 'stderr', text });
      resolve({ ok: false, code: 1, log: text, output: null });
      return;
    }

    activeBuilds.set(projectDir, child);

    const push = (stream, line) => {
      log += line + '\n';
      onOutput({ stream, text: line + '\n' });
    };
    streamLines(child.stdout, (line) => push('stdout', line));
    streamLines(child.stderr, (line) => push('stderr', line));

    child.on('error', (error) => {
      if (finished) return;
      finished = true;
      activeBuilds.delete(projectDir);
      const text = `Compiler error: ${error.message}\n`;
      onOutput({ stream: 'stderr', text });
      resolve({ ok: false, code: 1, log: log + text, output: null });
    });

    child.on('close', (code, signal) => {
      if (finished) return;
      finished = true;
      activeBuilds.delete(projectDir);
      const cancelled = signal === 'SIGTERM' || signal === 'SIGKILL';
      if (code === 0 && fs.existsSync(cmd.output)) {
        const size = fs.statSync(cmd.output).size;
        const text = `\nBuilt ${path.relative(projectDir, cmd.output)} (${size.toLocaleString()} bytes)\n`;
        onOutput({ stream: 'success', text });
        resolve({
          ok: true,
          code: 0,
          log: log + text,
          output: cmd.output,
          size,
          sources: cmd.sources
        });
      } else {
        const text = cancelled
          ? '\nBuild cancelled.\n'
          : `\nBuild failed (exit ${code ?? '?'}).\n`;
        onOutput({ stream: 'stderr', text });
        resolve({
          ok: false,
          code: code ?? 1,
          log: log + text,
          output: null,
          cancelled
        });
      }
    });
  });
}

function cancelBuild(dir) {
  const child = activeBuilds.get(path.resolve(dir));
  if (!child) return false;
  try {
    child.kill('SIGTERM');
  } catch {
    return false;
  }
  return true;
}

function isBuilding(dir) {
  return activeBuilds.has(path.resolve(dir));
}

module.exports = {
  outputPath,
  iconPath,
  buildProject,
  cancelBuild,
  isBuilding,
  friendlyMissing
};
